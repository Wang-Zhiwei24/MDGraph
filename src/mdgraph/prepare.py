def relaxation_cell_ok(values, angles, symmetry: str, *, rtol=1e-6) -> bool:
    basal_ok = np.isclose(values[0], values[1], rtol=rtol, atol=0)
    if min(values) <= 0 or not basal_ok:
        return False
    if symmetry == "hexagonal":
        return bool(np.allclose(angles, [90, 90, 120], atol=1e-4, rtol=0))
    return bool(
        np.isclose(values[0], values[2], rtol=rtol, atol=0)
        and np.allclose(angles, [90, 90, 90], atol=1e-4, rtol=0)
    )


def atomic_potential_setup(cfg: TaskConfig, filename: str | None, kind: str) -> str:
    potential = cfg.potential
    if kind != "lj_demo":
        if not filename and not potential.model:
            raise ValueError("A selected model is required")
        filename = filename or model_filename(potential.model)
    if kind == "deepmd":
        pair = f"pair_style deepmd {filename}\npair_coeff * *"
    elif kind == "eam":
        if len(cfg.structure.elements) != 1:
            raise ValueError("Single-element EAM requires one element")
        pair = f"pair_style eam\npair_coeff * * {filename}"
    elif kind in {"pace", "eam/alloy", "eam/fs", "sw", "tersoff"}:
        pair = f"pair_style {kind}\npair_coeff * * {filename} " + " ".join(cfg.structure.elements)
    elif kind == "lj_demo":
        pair = "pair_style lj/cut 8.5\npair_coeff * * 0.0103 3.4 8.5"
    else:
        raise ValueError("No executable pair style was selected")
    plugin = "plugin load plugin.so\n" if potential.plugin else ""
    return (
        "# Generated by mdgraph; units: eV, Angstrom, ps, bar\n"
        "units metal\natom_style atomic\nboundary p p p\nread_data structure.data\n"
        + plugin
        + pair
        + "\nneighbor 2.0 bin\nneigh_modify delay 0 every 1 check yes\n"
    )


def render_input(
    cfg: TaskConfig, filename: str | None = None, *, kind: str | None = None, relax_passes: int = 3
) -> str:
    p = cfg.protocol
    kind = kind or cfg.potential.kind
    if relax_passes not in {3, 4}:
        raise ValueError("Invalid relaxation profile")
    if kind == "water":
        model_id = filename or cfg.potential.water_model
        if model_id == "auto":
            raise ValueError("Select a water model before rendering the LAMMPS input")
        return render_dynamics(cfg, render_water_setup(model_id), molecular=True)
    setup = atomic_potential_setup(cfg, filename, kind)
    finish = (
        'write_data final.data nocoeff\nwrite_restart final.restart\nprint "MDGRAPH_COMPLETED"\n'
    )
    if p.ensemble == "relax":
        if p.relax_cell == "hexagonal":
            style = f"aniso {p.pressure_bar} couple xy scalexy yes"
        else:
            style = f"iso {p.pressure_bar}"
        relax = (
            f"fix cell all box/relax {style} vmax 0.001\n"
            "minimize 0.0 1.0e-10 10000 100000\nunfix cell\n"
        )
        # Reset the reference box and repeat before evaluating the final state without the fix.
        output = (
            setup
            + "min_style cg\nthermo 10\nthermo_style custom step pe press fmax\n"
            + relax * relax_passes
            + "thermo_style custom step atoms pe press pxx pyy pzz pxy pxz pyz lx ly lz fmax "
            "cella cellb cellc cellalpha cellbeta cellgamma\n"
            "thermo_modify format float %.15g flush yes lost error\nrun 0\n"
        )
        if p.elastic:
            return (
                output
                + "write_data final.data nocoeff\nwrite_restart final.restart\n"
                + render_elastic(setup)
                + 'print "MDGRAPH_COMPLETED"\n'
            )
        return output + finish
    return render_dynamics(cfg, setup)


def render_dynamics(
    cfg: TaskConfig,
    setup: str,
    *,
    molecular: bool = False,
    molecular_model: MolecularModel | None = None,
) -> str:
    """Render the equilibration and production segments with their recorded units."""
    p = cfg.protocol
    time_scale = 1.0 if molecular else 0.001
    pressure = p.pressure_bar / 1.01325 if molecular else p.pressure_bar
    rigid = molecular_model is not None and molecular_model.integration == "rigid"
    confined = molecular_model is not None and cfg.structure.molecular.geometry in {
        "graphene_slit",
        "cnt",
    }
    mobile = "water" if confined else "all"

    def integrator(ensemble):
        style = f"rigid/{ensemble}/small molecule" if rigid else ensemble
        fix = f"fix integrator {mobile} {style}"
        if ensemble != "nve":
            fix += f" temp {p.temperature_k} {p.temperature_k} {p.tdamp_fs * time_scale:.12g}"
        if ensemble == "npt":
            fix += f" iso {pressure:.12g} {pressure:.12g} {p.pdamp_fs * time_scale:.12g}"
        return fix

    if confined:
        # Keep the rigid-body integrator and MPI communication state across the sampling boundary.
        start = p.equilibration_steps
        return (
            setup + f"timestep {p.timestep_fs:.12g}\n"
            f"velocity water create {p.temperature_k} {p.seed} mom yes rot no dist gaussian\n"
            "compute water_thermal water temp\n" + integrator("nvt") + "\n"
            f"thermo {p.thermo_every}\n"
            "thermo_style custom step time temp pe ke etotal press vol atoms pxx pyy pzz lx ly lz density\n"
            "thermo_modify temp water_thermal flush yes lost error\n"
            f"dump traj all custom {p.dump_every} trajectory.lammpstrj id type x y z ix iy iz mol\n"
            f"dump_modify traj sort id delay {start}\n"
            f"restart {max(p.dump_every, p.steps // 2)} checkpoint.*.restart\n"
            f"run {start + p.steps}\nwrite_data final.data\nwrite_restart final.restart\n"
            'print "MDGRAPH_COMPLETED"\n'
        )

    minimization = "minimize 1.0e-8 1.0e-6 1000 10000\n" if p.minimize and not rigid else ""
    # Older LAMMPS versions cannot minimize under SHAKE. Enable it before dynamics.
    if molecular_model:
        bonds = " ".join(map(str, molecular_model.constrained_bond_types))
        constraint = "" if rigid else f"fix molecule_geometry all shake 0.0001 100 0 b {bonds}\n"
    else:
        constraint = "fix water_geometry all shake 0.0001 50 0 b 1 a 1\n" if molecular else ""
    extra = " pxx pyy pzz lx ly lz density" if molecular_model else ""
    thermo = f"thermo_style custom step time temp pe ke etotal press vol atoms{extra}\nthermo_modify flush yes lost error\n"
    equilibration = ""
    if p.equilibration_steps:
        every = max(1, min(p.thermo_every, p.equilibration_steps // 20))
        equilibration = (
            f"{integrator(p.equilibration_ensemble or p.ensemble)}\nthermo {every}\n"
            + thermo
            + f'print "MDGRAPH_EQUILIBRATION_BEGIN"\nrun {p.equilibration_steps}\n'
            'print "MDGRAPH_EQUILIBRATION_END"\nunfix integrator\n'
        )
    return (
        setup + minimization + f"timestep {p.timestep_fs * time_scale:.12g}\n"
        f"velocity {mobile} create {p.temperature_k} {p.seed} mom yes rot no dist gaussian\n"
        + constraint
        + equilibration
        + "reset_timestep 0\n"
        + integrator(p.ensemble)
        + "\n"
        + f"thermo {p.thermo_every}\n"
        + thermo
        + f"dump traj all custom {p.dump_every} trajectory.lammpstrj id type x y z ix iy iz"
        + (" mol\n" if molecular_model else "\n")
        + "dump_modify traj sort id\n"
        f"restart {max(p.dump_every, p.steps // 2)} checkpoint.*.restart\nrun {p.steps}\n"
        'write_data final.data\nwrite_restart final.restart\nprint "MDGRAPH_COMPLETED"\n'
    )


def build_structure(
    cfg: TaskConfig,
    folder: Path,
    *,
    wrap: bool = False,
    builder: str | None = None,
    molecular_model: MolecularModel | None = None,
) -> dict:
    """Build or import coordinates and freeze validated LAMMPS atom types."""
    folder.mkdir(parents=True, exist_ok=True)
    record = folder / "structure_build.json"
    if record.exists():
        saved = read_json(record)
        verify_files(folder, saved["files"])
        return saved
    s = cfg.structure
    if any(element not in atomic_numbers or not atomic_numbers[element] for element in s.elements):
        raise ValueError("Structure contains unknown chemical elements")
    if s.molecular:
        if molecular_model is None:
            raise ValueError("Select a molecular force field before constructing its topology")
        return build_molecular_structure(cfg, folder, molecular_model, builder or "regular_grid")
    source = {}
    tool = {"name": ASE_TOOL, "operation": "read and convert", "artifacts": []}
    builder = builder or available_builders(s)[0]
    if s.demo_argon:
        atoms = bulk("Ar", "fcc", a=5.26, cubic=True).repeat((4, 4, 4))
        mode = "argon_demo"
        tool["operation"] = "bulk and repeat"
    elif s.water_repeat:
        atoms = build_water_box(s.water_repeat, cfg.protocol.seed)
        mode = "periodic_water"
        source = {"water_molecules": s.water_repeat**3, "seed": cfg.protocol.seed}
        tool["operation"] = (
            "Build an explicit periodic water topology with seeded molecule orientations"
        )
    elif s.crystal:
        crystal = s.crystal
        atoms, tool = build_crystal(s, folder, builder)
        mode = f"{builder}_crystal"
        source = {"crystal": crystal.model_dump(mode="json")}
    else:
        if not Path(s.path).is_file():
            raise ValueError(f"Structure file not found: {s.path}")
        source = {"structure_sha256": sha256(Path(s.path))}
        mode = "import"
        options = {}
        if s.format == "lammps-data" or Path(s.path).suffix == ".data":
            options = {"atom_style": "atomic", "units": "metal"}
            s_format = "lammps-data"
            options["Z_of_type"] = {i + 1: atomic_numbers[e] for i, e in enumerate(s.elements)}
        else:
            s_format = s.format
        atoms = read(s.path, format=s_format, **options)
    if len(atoms) < 2 or not atoms.pbc.all() or atoms.get_volume() <= 0:
        raise ValueError("Requires at least 2 atoms in a 3D periodic nonzero cell")
    if not np.isfinite(atoms.positions).all() or not np.isfinite(atoms.cell.array).all():
        raise ValueError("Non-finite structure")
    if set(atoms.get_chemical_symbols()) != set(s.elements):
        raise ValueError("Structure species must match explicit elements/type mapping")
    if cfg.protocol.ensemble == "relax":
        repeat = s.crystal.repeat if s.crystal else (1, 1, 1)
        if not relaxation_cell_ok(
            atoms.cell.lengths() / repeat, atoms.cell.angles(), cfg.protocol.relax_cell
        ):
            raise ValueError("Initial cell does not match the constrained lattice symmetry")
    distances = neighbor_list("d", atoms, cfg.validation.min_pair_distance_angstrom)
    if len(distances):
        raise ValueError("Overlapping atoms: below minimum pair-distance threshold")
    if wrap:
        atoms.wrap()
    if s.water_repeat:
        write_water_data(folder / "structure.data", atoms)
    else:
        write(
            folder / "structure.data",
            atoms,
            format="lammps-data",
            specorder=s.elements,
            atom_style="atomic",
            units="metal",
            masses=True,
        )
    write(folder / "initial.extxyz", atoms)
    result = {
        "mode": mode,
        "wrapped": wrap,
        "atoms": len(atoms),
        "elements": s.elements,
        "element_counts": {e: atoms.symbols.count(e) for e in s.elements},
        "source": source,
        "tool": tool,
        "files": {
            name: sha256(folder / name)
            for name in ("structure.data", "initial.extxyz", *tool["artifacts"])
        },
    }
    atomic_json(record, result)
    return result


def write_input(
    cfg: TaskConfig, folder: Path, structure: dict, potential: dict, *, relax_passes: int = 3
) -> dict:
    """Combine immutable inputs and record a hash manifest for the solver."""
    manifest_path = folder / "manifest.json"
    if manifest_path.exists():
        return verified_manifest(folder)
    files = {**structure["files"], **potential["files"]}
    verify_files(folder, files)
    if cfg.structure.molecular:
        model = MolecularModel.model_validate(read_json(folder / potential["filename"]))
        script = render_dynamics(
            cfg,
            molecular_setup(cfg.structure.molecular, model, cfg.potential.wall_interface),
            molecular=True,
            molecular_model=model,
        )
    else:
        script = render_input(
            cfg,
            potential.get("water_model") or potential["filename"],
            kind=potential["kind"],
            relax_passes=relax_passes,
        )
    (folder / "in.lammps").write_text(script, encoding="utf-8", newline="\n")
    for name in ("in.lammps", "structure_build.json", "potential_selection.json"):
        files[name] = sha256(folder / name)
    sources = dict(structure["source"])
    if potential.get("model_sha256"):
        sources["model_sha256"] = potential["model_sha256"]
    if "plugin.so" in files:
        sources["plugin_sha256"] = files["plugin.so"]
    molecular = potential["kind"] in {"water", "molecular"}
    result = {
        "atoms": structure["atoms"],
        "elements": structure["elements"],
        "units": "real" if molecular else "metal",
        "atom_style": "full" if molecular else "atomic",
        "potential_kind": potential["kind"],
        "sources": sources,
        "files": files,
    }
    if cfg.potential.wall_interface:
        proof = molecular_preflight(cfg, folder, script, structure["atoms"])
        result["wall_preflight"] = proof
        files["wall_preflight.json"] = sha256(folder / "wall_preflight.json")
    atomic_json(manifest_path, result)
    return result


def molecular_preflight(cfg: TaskConfig, folder: Path, script: str, expected_atoms: int) -> dict:
    """Initialize the prepared solver input and evaluate forces without advancing MD."""
    setup, separator, _ = script.partition("\nrun ")
    if not separator:
        raise ValueError("The composed solver script has no dynamics run to check")
    probe = folder / "wall_preflight.in"
    probe.write_text(
        setup + "\nthermo 1\nthermo_style custom step atoms pe fmax\nrun 0\n"
        "variable p_atoms equal atoms\nvariable p_energy equal pe\nvariable p_force equal fmax\n"
        'print "MDGRAPH_WALL_PROBE ${p_atoms} ${p_energy} ${p_force}"\n',
        encoding="utf-8",
        newline="\n",
    )
    env = {
        key: value
        for key, value in os.environ.items()
        if key.upper()
        in {
            "PATH",
            "LD_LIBRARY_PATH",
            "SYSTEMROOT",
            "WINDIR",
            "TEMP",
            "TMP",
            "LANG",
            "LC_ALL",
        }
    }
    env["OMP_NUM_THREADS"] = "1"
    try:
        result = subprocess.run(
            [*cfg.execution.command, "-in", probe.name, "-log", "none"],
            cwd=folder,
            env=env,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            errors="replace",
            timeout=60,
        )
    except subprocess.TimeoutExpired as exc:
        raise ValueError("LAMMPS run 0 did not finish in 60 seconds") from exc
    (folder / "wall_preflight.log").write_text(result.stdout + result.stderr, encoding="utf-8")
    match = re.search(r"^MDGRAPH_WALL_PROBE\s+(\S+)\s+(\S+)\s+(\S+)$", result.stdout, re.M)
    if result.returncode or not match:
        error = next(
            (line for line in result.stdout.splitlines() if line.startswith("ERROR")), result.stderr
        )
        raise ValueError(f"LAMMPS run 0 failed: {error[:600] or result.returncode}")
    atoms, energy, force = map(float, match.groups())
    if atoms != expected_atoms or not all(map(math.isfinite, (energy, force))):
        raise ValueError("LAMMPS run 0 did not preserve the planned atom count and finite forces")
    proof = {
        "status": "passed",
        "checks": "LAMMPS run 0 on the composed molecular structure",
        "atoms": int(atoms),
        "potential_energy_kcal_mol": energy,
        "max_force_kcal_mol_angstrom": force,
        "probe_sha256": sha256(probe),
        "log_sha256": sha256(folder / "wall_preflight.log"),
    }
    atomic_json(folder / "wall_preflight.json", proof)
    return proof


def verified_manifest(folder: Path) -> dict:
    manifest = read_json(folder / "manifest.json")
    verify_files(folder, manifest["files"])
    return manifest


def prepare(cfg: TaskConfig, folder: Path) -> dict:
    if (folder / "manifest.json").exists():
        return verified_manifest(folder)
    if cfg.structure.molecular:
        potential = select_molecular_model(cfg, folder, None)
        model = MolecularModel.model_validate(read_json(folder / potential["filename"]))
        structure = build_structure(cfg, folder, molecular_model=model)
        return write_input(cfg, folder, structure, potential)
    # Keep the existing explicit-model preflight; only a catalog needs built composition.
    if not cfg.potential.catalog:
        potential = retrieve_potential(cfg, folder)
        structure = build_structure(cfg, folder)
        return write_input(cfg, folder, structure, potential)
    structure = build_structure(cfg, folder)
    potential = retrieve_potential(cfg, folder, element_counts=structure.get("element_counts"))
    return write_input(cfg, folder, structure, potential)
